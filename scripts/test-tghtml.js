const assert = require('assert');
const { mdToTelegramHtml: h, splitMarkdown } = require('../electron/remote/tghtml.js');
assert.strictEqual(h('Hello **world**'), 'Hello <b>world</b>');
assert.strictEqual(h('## Heading'), '<b>Heading</b>');
assert.strictEqual(h('- one\n- two'), '• one\n• two');
assert.strictEqual(h('`a<b` and *italic*'), '<code>a&lt;b</code> and <i>italic</i>');
assert.strictEqual(h('```bash\nollama run x\n```'), '<pre><code class="language-bash">ollama run x</code></pre>');
assert.strictEqual(h('```\n<a> & b\n```'), '<pre>&lt;a&gt; &amp; b</pre>');
assert.strictEqual(h('[Qwen](https://ollama.com/library/qwen3?a=1&b=2)'), '<a href="https://ollama.com/library/qwen3?a=1&amp;b=2">Qwen</a>');
assert.strictEqual(h('2 * 3 * 4 = 24'), '2 * 3 * 4 = 24');
assert.strictEqual(h('snake_case_name stays'), 'snake_case_name stays');
assert.strictEqual(h('> quote\n> second'), '<blockquote>quote\nsecond</blockquote>');
assert.ok(/^<pre>a {2}b\n1 {2}2<\/pre>$/.test(h('| a | b |\n|---|---|\n| 1 | 2 |')), h('| a | b |\n|---|---|\n| 1 | 2 |'));
assert.ok(!/\*\*|##/.test(h('## **Qwen3** for you\n\n**My ranking:**\n\n1. **Qwen3 4B** — balanced')));
const long = '```js\n' + 'x\n'.repeat(3000) + '```\ntail';
const parts = splitMarkdown(long, 1000);
assert.ok(parts.length > 3 && parts.every((p) => p.length <= 1040));
assert.ok(parts.every((p) => (p.match(/```/g) || []).length % 2 === 0), 'fences balanced');
assert.ok(splitMarkdown('a\n\nb', 1000).length === 1);
console.log('tghtml: all tests passed');
